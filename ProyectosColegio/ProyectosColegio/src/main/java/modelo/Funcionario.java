package modelo;

/**
 *
 * @author usuario
 */
public class Funcionario {
    private int id;
    private String rut;
    private String nombre;

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getRut() {
        return rut;
    }

    public void setRut(String rut) {
        this.rut = rut;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    @Override
    public String toString() {
        return "Funcionario{" + "id=" + id + ", rut=" + rut + ", nombre=" + nombre + '}';
    }
    
    
    
}
